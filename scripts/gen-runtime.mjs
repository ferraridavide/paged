// Generates public/runtime/*.js: tiny ES modules that re-export the editor's
// own React, ReactDOM and SDK instances. index.html's import map points the
// bare specifiers "react", "react-dom", … at these files, so custom components
// and every package loaded from the CDN share one React with the editor.
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public/runtime");
mkdirSync(out, { recursive: true });

const SDK_EXPORTS = ["defineElement", "Editable", "useElement", "useElementState", "usePageInfo"];

const modules = {
  "react.js": ["react", Object.keys(require("react"))],
  "react-jsx-runtime.js": ["react/jsx-runtime", Object.keys(require("react/jsx-runtime"))],
  "react-dom.js": ["react-dom", Object.keys(require("react-dom"))],
  "sdk.js": ["@paged/sdk", SDK_EXPORTS],
};

const ident = /^[A-Za-z_$][\w$]*$/;
for (const [file, [specifier, names]] of Object.entries(modules)) {
  const exported = names.filter((n) => n !== "default" && ident.test(n));
  writeFileSync(
    join(out, file),
    `// Generated by scripts/gen-runtime.mjs. Re-exports the editor's own "${specifier}".
const ns = globalThis.__PAGED_RUNTIME__[${JSON.stringify(specifier)}];
const m = ns.default ?? ns;
export default m;
export const { ${exported.join(", ")} } = { ...m, ...ns };
`,
  );
}
console.log(`Generated ${Object.keys(modules).length} runtime modules in public/runtime/`);
